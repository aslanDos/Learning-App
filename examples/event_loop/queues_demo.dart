// В консольном уроке print нужен для наблюдения за порядком выполнения.
// ignore_for_file: avoid_print

import 'dart:async';

void main() {
  print('1. Начало main');

  // Откладываем функцию в очередь событий.
  Future<void>(() {
    print('5. Первое событие');

    // Эта микрозадача выполнится до следующего события.
    scheduleMicrotask(() {
      print('6. Микрозадача из первого события');
    });
  });

  // Микрозадачи имеют приоритет перед следующими событиями.
  scheduleMicrotask(() {
    print('3. Первая микрозадача');
  });

  Future<void>.microtask(() {
    print('4. Вторая микрозадача');
  });

  // Второе событие ждёт своей очереди.
  Future<void>(() {
    print('7. Второе событие');
  });

  // Синхронный код заканчивается до обработки обеих очередей.
  print('2. Конец main');
}
